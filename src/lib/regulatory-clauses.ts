/**
 * The clause lists offered to a person on the review screen, one list per instrument.
 *
 * Why only three instruments live here. A clause list is only useful to a person if the
 * publisher titles its paragraphs. EAWR 1989, ESQCR 2002 and the Building Regulations 2010
 * each print a heading against every numbered unit on their contents page, so a picker can
 * offer "4 - Systems, work activities and protective equipment" and a reader can see what
 * they are choosing. BS 7671 (licensed, and not published on a page that can be checked),
 * HSR25, HSG85 and Approved Document P title nothing on their contents, so their lists would
 * be numbers alone - a picker of several hundred bare numbers, which is not a choice a person
 * can make. Those instruments therefore carry no list here, and the clause picker simply does
 * not appear for them. That grouping decision is deliberate and is not made by a screen.
 *
 * Every entry was taken from the publisher's own contents page, verbatim - number and heading
 * exactly as printed, nothing invented, inferred, tidied or reordered. Each set names the page
 * it was read from and the date, so a reader can check all of it.
 *
 * Two things the source does that are carried deliberately rather than corrected:
 *
 *  - ESQCR 2002 regulation 20A is printed with NO heading (the contents page and the
 *    regulation page both give none). A clause with no heading has nothing to print beside the
 *    reference, so it is left out of the list rather than given an invented one. That set
 *    therefore offers 41 of the 42 printed units.
 *  - The Building Regulations 2010 print regulations 44ZB and 44ZC twice each, with the same
 *    number and the same heading (Part 9A exists in separate England and non-England versions).
 *    A list keyed on the number cannot tell the two copies apart and they print identically, so
 *    the second copy is dropped. That set therefore offers 176 units from 178 printed entries.
 *
 * This is DATA. A prompt, a schema or a renderer must never read it: the clause is chosen by a
 * person from the list, and only the chosen number is stored. Nothing here is ever sent to a
 * model.
 *
 * Nothing in this module may be added to an AI prompt, an output schema or the field guide.
 * The instrument's clauses are a closed list for a person; the model's own citation surface is
 * the instrument id list on the template, and it never reaches beyond it.
 *
 * @see src/lib/survey-types.ts - ClauseSet, clausesOf, resolveClause, clauseLabel
 */
